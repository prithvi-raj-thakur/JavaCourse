package Basics;

public class doubleDatatype {
    public static void main(String[] args) {
        double x = 5;
        double y = 2;
        double z = 5 / 2;
        System.out.println(z);
        double a = x / y ;
        System.out.println(a);
        double b = 5.0 / 2;
        System.out.println(b);
        double c = 5 / 2.0;
        System.out.println(c);
        double d = 5.0 / 2.0 ;
        System.out.println(d);
    }
}
