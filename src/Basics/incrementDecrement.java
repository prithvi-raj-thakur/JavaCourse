package Basics;

import java.util.Scanner;

public class incrementDecrement {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x);
        x++;
        System.out.println(x);
        x--;
        System.out.println(x);
        --x;
        System.out.println(x);
        ++x;
        System.out.println(x);
    }
}
